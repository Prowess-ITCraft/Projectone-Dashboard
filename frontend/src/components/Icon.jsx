export function Icon({ name, size = 18, weight = 'regular', className = '', ...rest }) {
  const Glyph = MAP[name] || PackageIcon;
  return <Glyph size={size} weight={weight} className={`ico ${className}`} aria-hidden="true" {...rest} />;
}
